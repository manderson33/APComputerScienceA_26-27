public class FormattingExpressions {
    static void main(){
        //Using escape sequences
        //printing double quotes
        System.out.println("School is \"cool\"!");
        //printing a backslash
        System.out.println("Large\\Medium\\Small");
        //moves texts to the next line in one print statement
        System.out.println("ACS is warm \nand cool");
        //generates a tab space in between
        System.out.println("Name\tGrade");

    }
}
